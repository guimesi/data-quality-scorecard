def _one_click_app_no_run(**state) -> AppTest:
    """Build (but don't run) a One-click app so a monkeypatch can be applied
    before the first render."""
    at = AppTest.from_file(APP_PATH, default_timeout=60)
    at.session_state["app_mode"] = "one_click"
    at.session_state["current_step"] = "one_click"
    for k, v in state.items():
        at.session_state[k] = v
    return at


def test_no_applicable_custom_dqrs_blocks_generate(monkeypatch):
    """A selected system with no custom rules blocks Generate with a clear
    error (One-click is custom-only)."""
    import ui.step_one_click as oc_ui

    monkeypatch.setattr(oc_ui, "get_available_custom_dqr_rules", lambda code: [])
    at = _one_click_app_no_run(domain="cost_estimate", selected_systems=["EPT"])
    at.run()
    assert any("applicable Custom DQRs" in e.value for e in at.error)
    assert at.button(key="oneclick_generate").disabled


def test_generate_nothing_scored_shows_error_and_stays(monkeypatch):
    """When the pipeline scores nothing, the user stays on the step with the
    skip reasons surfaced."""
    import ui.step_one_click as oc_ui
    from src.one_click import OneClickResult

    monkeypatch.setattr(
        oc_ui, "run_one_click",
        lambda *a, **k: OneClickResult(
            domain_code="cost_estimate", requested_systems=["EPT"],
            products={}, skipped={"EPT": "the project filter matched 0 rows"},
        ),
    )
    at = _one_click_app_no_run(domain="cost_estimate", selected_systems=["EPT"])
    at.run()
    at.button(key="oneclick_generate").click().run()
    assert at.session_state["current_step"] == "one_click"  # stayed put
    assert any("could not score" in e.value for e in at.error)


def test_generate_blocking_error_keeps_user_on_step(monkeypatch):
    import ui.step_one_click as oc_ui
    from src.one_click import OneClickError

    def _boom(*a, **k):
        raise OneClickError("databricks exploded")

    monkeypatch.setattr(oc_ui, "run_one_click", _boom)
    at = _one_click_app_no_run(domain="cost_estimate", selected_systems=["EPT"])
    at.run()
    at.button(key="oneclick_generate").click().run()
    assert at.session_state["current_step"] == "one_click"
    assert any("databricks exploded" in e.value for e in at.error)


def test_generate_csv_failure_is_recorded_but_nonblocking(monkeypatch):
    """A CSV-export failure is recorded and surfaced on the dashboard but
    does not block the (valid) scorecards."""
    import ui.step_one_click as oc_ui

    def _boom_csv(*a, **k):
        raise RuntimeError("csv boom")

    monkeypatch.setattr(oc_ui, "_build_rowscores_csv", _boom_csv)
    at = _one_click_app_no_run(domain="cost_estimate", selected_systems=["EPT"])
    at.run()
    at.button(key="oneclick_generate").click().run()
    # Scorecards still generated and we still land on the dashboard.
    assert at.session_state["current_step"] == "dashboard"
    assert "EPT" in at.session_state["scorecards"]
    assert at.session_state["one_click_summary"]["csv_errors"]
    assert any("CSV export could not be prepared" in e.value for e in at.error)
